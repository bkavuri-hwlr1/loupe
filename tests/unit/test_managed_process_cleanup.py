def test_process_cleanup_scan_does_not_hold_publisher_lock(
    environment: Environment,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    env = environment
    env.manager.remember_process_policy(env.workspace)
    original = env.manager._process_unknown_paths
    observations: list[bool] = []

    def inspected(*args: Any, **kwargs: Any) -> Any:
        acquired: list[bool] = []

        def lock_probe() -> None:
            held = env.manager.lock.acquire(timeout=0.5)
            acquired.append(held)
            if held:
                env.manager.lock.release()

        worker = threading.Thread(target=lock_probe)
        worker.start()
        worker.join(1)
        observations.extend(acquired)
        return original(*args, **kwargs)

    monkeypatch.setattr(env.manager, "_process_unknown_paths", inspected)
    (env.private / "build").mkdir()
    env.close()
    assert observations and all(observations)
    assert not env.private.exists()


def test_cleaning_state_crash_replays_generated_runtime_scrub(
    environment: Environment,
) -> None:
    env = environment
    env.manager.remember_process_policy(env.workspace)
    (env.private / "build").mkdir()
    (env.private / "build/heartbeat").write_text("private process bytes")
    env.store.close_session("process-cleanup")
    with env.store.connection() as con:
        con.execute(
            "UPDATE workspaces SET state='cleaning' WHERE workspace_id=?",
            (env.workspace.workspace_id,),
        )
    env.manager.recover()
    assert not env.private.exists()
    assert env.store.get_workspace(env.workspace.workspace_id).state == "removed"
    assert not (env.archive / "files/build").exists()


def test_foreign_process_policy_receipt_refuses_launch(
    environment: Environment,
) -> None:
    from llm_cli.errors import LlmCoordError

    env = environment
    env.manager.remember_process_policy(env.workspace)
    assert env.workspace.git_dir is not None
    path = Path(env.workspace.git_dir) / "loupe-process-policy.json"
    receipt = json.loads(path.read_text())
    receipt["token"] = "foreign-owner"
    path.write_text(json.dumps(receipt))
    with pytest.raises(LlmCoordError, match="receipt changed"):
        env.manager.remember_process_policy(env.workspace)


def test_policy_change_after_first_process_keeps_next_launch_available(
    environment: Environment,
) -> None:
    env = environment
    env.manager.remember_process_policy(env.workspace)
    (env.private / ".gitignore").write_text(".env\n*.py\n")
    env.manager.remember_process_policy(env.workspace)
    (env.private / "user.py").write_text("preserve source")
    env.close()
    assert (env.private / "user.py").read_text() == "preserve source"
