from llm_cli.workspace.isolated import IsolatedWorkspaceManager


@dataclass
class Environment:
    manager: IsolatedWorkspaceManager
    store: ControlStore
    workspace: WorkspaceRecord
    primary: Path
    private: Path

    def close(self) -> None:
        self.store.close_session("process-cleanup")
        self.manager.cleanup_closed("process-cleanup")

    @property
    def archive(self) -> Path:
        return self.private.parent / (".recovery-" + self.workspace.workspace_id)


@pytest.fixture
def environment(
    tmp_path: Path,
    repository_factory: Callable[[Path, dict[str, str]], Path],
) -> Environment:
    primary = repository_factory(
        tmp_path, {"a.py": "value = 1\n", ".gitignore": ".env\nbuild/\n*.log\n"}
    )
    (primary / ".env").write_text("private opening runtime")
    store = ControlStore(tmp_path / "control.sqlite3")
    store.initialize()
    repository = store.register_repository(
        repo_key="b" * 64,
        display_name="process cleanup",
        git_common_dir=str(primary / ".git"),
        main_worktree_path=str(primary),
        target_ref="refs/heads/main",
        path_case_insensitive=False,
    )
    checkout = store.ensure_checkout(
        repository=repository,
        canonical_path=str(primary),
        git_common_dir=str(primary / ".git"),
    )
    manager = IsolatedWorkspaceManager(
        store,
        tmp_path / "private",
        tmp_path / "candidates",
        threading.RLock(),
        lambda _: None,
    )
    workspace, _ = manager.open(checkout, "process-cleanup", approved_secrets=(".env",))
    store.open_session(
        session_id="process-cleanup",
        checkout_id=checkout.checkout_id,
        resume_token_hash=hashlib.sha256(b"cleanup").hexdigest(),
        provider="fake",
        model="fake",
        workspace_id=workspace.workspace_id,
        workspace_mode="isolated",
    )
    return Environment(
        manager, store, workspace, primary, Path(workspace.canonical_path)
    )


def test_new_ignored_process_runtime_is_scrubbed_without_archiving(
    environment: Environment,
) -> None:
    env = environment
    env.manager.remember_process_policy(env.workspace)
    (env.private / "build/nested").mkdir(parents=True)
    (env.private / "build/nested/heartbeat").write_text("private generated bytes")
    (env.private / "server.log").write_text("private generated log")
    env.close()
    assert not env.private.exists()
    owner = json.loads((env.archive / "owner.json").read_text())
    assert {"build", "server.log"} <= set(owner["private_paths"])
    assert not (env.archive / "files/build").exists()
    assert not (env.archive / "files/server.log").exists()
    assert (env.archive / "files/a.py").read_text() == "value = 1\n"


def test_unknown_ordinary_source_survives_process_cleanup(
    environment: Environment,
) -> None:
    env = environment
    env.manager.remember_process_policy(env.workspace)
    (env.private / "user.py").write_text("keep unknown source")
    (env.private / "build").mkdir()
    (env.private / "build/output").write_text("private generated runtime")
    env.close()
    assert (env.private / "user.py").read_text() == "keep unknown source"
    assert not (env.private / "build").exists()
    assert not (env.private / ".env").exists()
    assert env.store.get_workspace(env.workspace.workspace_id).state == "quarantined"


def test_preexisting_unknown_ignored_path_is_never_claimed(
    environment: Environment,
) -> None:
    env = environment
    (env.private / "build").mkdir()
    (env.private / "build/user-output").write_text("preexisting user bytes")
    env.manager.remember_process_policy(env.workspace)
    env.close()
    assert (env.private / "build/user-output").read_text() == "preexisting user bytes"
    assert not (env.private / ".env").exists()


@pytest.mark.parametrize("before_launch", [False, True])
def test_changed_ignore_policy_never_authorizes_generated_source_deletion(
    environment: Environment,
    before_launch: bool,
) -> None:
    env = environment
    if not before_launch:
        env.manager.remember_process_policy(env.workspace)
    (env.private / ".gitignore").write_text(".env\nbuild/\nuser.py\n")
    (env.private / "user.py").write_text("preserve policy-reclassified source")
    if before_launch:
        env.manager.remember_process_policy(env.workspace)
    env.close()
    assert (
        env.private / "user.py"
    ).read_text() == "preserve policy-reclassified source"
    assert not (env.private / ".env").exists()
    assert env.store.get_workspace(env.workspace.workspace_id).state == "quarantined"


